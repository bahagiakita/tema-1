#!/usr/bin/env node

/**
 * ============================================================
 * BahagiaKita — Supabase Table & SQL Generator
 * ============================================================
 * Skrip sederhana untuk menghasilkan SQL & panduan markdown (.md)
 * otomatis berdasarkan nama pasangan/klien (Opsi A - Multi Client 1 Database).
 *
 * Penggunaan:
 *   1. Interaktif: node scripts/generate-supabase-table.js
 *   2. Argumen:   node scripts/generate-supabase-table.js ahmad-fatimah
 * ============================================================
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

/**
 * Core generator logic (Dapat diekspor dan digunakan di web app / frontend UI)
 * @param {string} rawInput - Nama pasangan atau nama tabel (contoh: "Ahmad & Fatimah" atau "ahmad_fatimah")
 * @returns {object} { cleanSlug, tableName, fileName, sql, markdownContent }
 */
function generateSupabaseSetup(rawInput) {
  if (!rawInput || !rawInput.trim()) {
    throw new Error('Nama pasangan / nama tabel tidak boleh kosong.');
  }

  // Normalisasi input menjadi format slug tabel database
  const cleanSlug = rawInput
    .trim()
    .toLowerCase()
    .replace(/^rsvp_/, '') // Hapus prefix rsvp_ jika user sudah mengetiknya
    .replace(/[^a-z0-9]+/g, '_') // Ganti spasi & karakter khusus menjadi underscore
    .replace(/^_+|_+$/g, ''); // Hapus underscore di awal/akhir

  if (!cleanSlug) {
    throw new Error('Nama yang dimasukkan tidak valid (hanya karakter alfanumerik yang didukung).');
  }

  const tableName = cleanSlug;
  const fileSlug = cleanSlug.replace(/_/g, '-');
  const fileName = `supabase-${fileSlug}.md`;
  const formattedClientName = cleanSlug
    .split('_')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');

  // Template SQL yang sudah 100% FIX, aman, dan idempotent
  const sql = `-- ============================================================
-- SQL SETUP SUPABASE UNTUK TABEL: ${tableName}
-- Klien: ${formattedClientName}
-- Generated by BahagiaKita Generator
-- ============================================================

-- 1. Buat Tabel Utama
CREATE TABLE IF NOT EXISTS public.${tableName} (
    id BIGSERIAL PRIMARY KEY,
    guest_name VARCHAR(100) NOT NULL,
    attendance VARCHAR(20) NOT NULL DEFAULT 'hadir', -- 'hadir' atau 'tidak_hadir'
    message TEXT,
    user_id VARCHAR(100) DEFAULT 'anonymous',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Buat Index Sorting & User
CREATE INDEX IF NOT EXISTS idx_${tableName}_created_at ON public.${tableName} (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_${tableName}_user_id ON public.${tableName} (user_id);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.${tableName} ENABLE ROW LEVEL SECURITY;

-- 4. Kebijakan RLS (Public Read, Insert, Update, Delete)
DROP POLICY IF EXISTS "Allow public read" ON public.${tableName};
CREATE POLICY "Allow public read"
ON public.${tableName} FOR SELECT
TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Allow public insert" ON public.${tableName};
CREATE POLICY "Allow public insert"
ON public.${tableName} FOR INSERT
TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update" ON public.${tableName};
CREATE POLICY "Allow public update"
ON public.${tableName} FOR UPDATE
TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete" ON public.${tableName};
CREATE POLICY "Allow public delete"
ON public.${tableName} FOR DELETE
TO anon, authenticated USING (true);

-- 5. Aktifkan Supabase Realtime (Aman & Idempotent)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
      AND schemaname = 'public' 
      AND tablename = '${tableName}'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.${tableName};
  END IF;
END $$;
`;

  // Output Markdown yang rapi & siap pakai
  const markdownContent = `# Setup Supabase — ${tableName}

> **Klien / Pasangan**: **${formattedClientName}**  
> **Nama Tabel**: \`${tableName}\`  
> **Tanggal Dibuat**: ${new Date().toISOString().split('T')[0]}  

---

## 1. Salin & Jalankan Script SQL ini di Supabase SQL Editor

Buka dashboard Supabase > menu **SQL Editor** > **New Query**, lalu salin dan jalankan seluruh script di bawah ini:

\`\`\`sql
${sql}\`\`\`

---

## 2. Update Konfigurasi di \`wedding-config.js\`

Buka file \`wedding-config.js\` pada proyek undangan klien ini, lalu pastikan bagian \`tableName\` diisi dengan:

\`\`\`javascript
  supabase: {
    enabled: true,
    url: "https://<YOUR-PROJECT-ID>.supabase.co", // Project URL Supabase Anda
    anonKey: "<YOUR-PUBLISHABLE-OR-ANON-KEY>",   // Publishable Key (sb_publishable_...) atau Legacy Anon Key
    tableName: "${tableName}"               // <--- Nama tabel klien ini
  },
\`\`\`

---

## 3. Langkah Verifikasi
1. Buka website undangan di browser.
2. Coba kirim 1 ucapan & doa di seksi RSVP.
3. Buka menu **Table Editor** di Supabase > pilih tabel \`${tableName}\` untuk memastikan data masuk dengan sukses.
`;

  return {
    cleanSlug,
    tableName,
    fileName,
    formattedClientName,
    sql,
    markdownContent
  };
}

// Export jika di-require dari file lain (misal untuk API/Web)
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { generateSupabaseSetup };
}

// --- CLI Execution Handler ---
if (require.main === module) {
  const args = process.argv.slice(2);

  function processAndSave(input) {
    try {
      const result = generateSupabaseSetup(input);
      const outputDir = path.resolve(__dirname, '..', 'supabase-output');

      if (!fs.existsSync(outputDir)) {
        fs.mkdirSync(outputDir, { recursive: true });
      }

      const filePath = path.join(outputDir, result.fileName);
      fs.writeFileSync(filePath, result.markdownContent, 'utf8');

      console.log('\n✅ BERHASIL MEMBUAT FILE SQL & DOKUMENTASI!');
      console.log('───────────────────────────────────────────────────────');
      console.log(`📁 File tersimpan di : supabase-output/${result.fileName}`);
      console.log(`🏷️  Nama Tabel       : ${result.tableName}`);
      console.log(`👥 Klien             : ${result.formattedClientName}`);
      console.log('───────────────────────────────────────────────────────');
      console.log('💡 Langkah selanjutnya:');
      console.log(`   1. Buka file supabase-output/${result.fileName}`);
      console.log('   2. Salin isi script SQL dan jalankan di SQL Editor Supabase.');
      console.log(`   3. Set tableName: "${result.tableName}" di wedding-config.js.`);
      console.log('───────────────────────────────────────────────────────\n');
    } catch (err) {
      console.error('\n❌ Terjadi kesalahan:', err.message, '\n');
      process.exit(1);
    }
  }

  if (args.length > 0) {
    const input = args.join(' ');
    processAndSave(input);
  } else {
    const rl = readline.createInterface({
      input: process.stdin,
      output: process.stdout
    });

    console.log('\n=======================================================');
    console.log(' BahagiaKita — Supabase Table & SQL Generator');
    console.log('=======================================================');
    rl.question('Masukkan nama pasangan / klien (contoh: ahmad-fatimah): ', function (answer) {
      rl.close();
      if (!answer.trim()) {
        console.log('Operasi dibatalkan: input kosong.\n');
        process.exit(0);
      }
      processAndSave(answer);
    });
  }
}
